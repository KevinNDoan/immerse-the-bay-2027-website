// Fails when the site's source breaks the house copy rules:
// no em dashes, no dot separators, no emoji, and no small uppercase labels (eyebrows).
//   npm run check:copy
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";

const root = join(import.meta.dirname, "..");
const dirs = ["src"];
const exts = /\.(tsx?|css|mdx?)$/;
const skip = new Set(["src/components/ui"]); // generated by shadcn

const rules = [
  { name: "em dash", re: /—/ },
  { name: "dot separator", re: /[·•∙●・]/ },
  { name: "emoji", re: /\p{Extended_Pictographic}/u },
  { name: "eyebrow (uppercase label)", re: /\buppercase\b|text-transform:\s*uppercase/ },
];

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const rel = relative(root, p);
    if ([...skip].some((s) => rel.startsWith(s))) continue;
    if (statSync(p).isDirectory()) yield* walk(p);
    else if (exts.test(name)) yield p;
  }
}

let failures = 0;
for (const d of dirs) {
  for (const file of walk(join(root, d))) {
    const lines = readFileSync(file, "utf8").split("\n");
    lines.forEach((line, i) => {
      for (const r of rules) {
        if (r.re.test(line)) {
          failures++;
          console.error(`${relative(root, file)}:${i + 1}  ${r.name}: ${line.trim().slice(0, 100)}`);
        }
      }
    });
  }
}
if (failures) {
  console.error(`\n${failures} copy rule violation(s).`);
  process.exit(1);
}
console.log("Copy rules: clean.");
